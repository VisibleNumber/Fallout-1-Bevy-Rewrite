import assert from 'node:assert/strict';
import {ScriptGame} from './script-runtime.mjs';
const game=new ScriptGame();
let r=game.openOverseer();
assert.equal(r.status,'dialogue');
assert.equal(r.dialogue.options.length,1);
assert.equal(r.dialogue.options[0].procedure,'over08');
const first=r.dialogue.reply.text;
const snapshot=JSON.stringify(r.session);
assert.throws(()=>game.choose(r.session,0,r.session.step-1),/Stale/);
assert.equal(JSON.stringify(r.session),snapshot);
r=game.choose(JSON.parse(snapshot),0,r.session.step);
assert.equal(r.status,'dialogue');
assert.equal(r.dialogue.options[0].procedure,'overend');
r=game.choose(JSON.parse(JSON.stringify(r.session)),0,r.session.step);
assert.equal(r.status,'halted');
assert.equal(r.session.phase,'closed');
r=game.reopen(JSON.parse(JSON.stringify(r.session)),[],43);
assert.equal(r.status,'dialogue');
assert.notEqual(r.dialogue.reply.text,first);
assert.match(r.dialogue.reply.text,/have the chip/);
const diplomat=game.openOverseer({characterPath:'premade/diplomat.gcd'});
assert.equal(diplomat.status,'dialogue');
assert.equal(diplomat.dialogue.options.length,2);
console.log('Original OVER.INT: actual replies, Intelligence filtering, callbacks, JSON persistence, repeat visits and stale-choice rejection passed');
